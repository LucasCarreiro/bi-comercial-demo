import {esc} from './charts.js';

let currentJob=null;
function settlePrintLayout(promise,timeout){return new Promise((resolve,reject)=>{const timer=setTimeout(resolve,timeout);Promise.resolve(promise).then(value=>{clearTimeout(timer);resolve(value);},error=>{clearTimeout(timer);reject(error);});});}
/** Two metric snapshots, one local print job. The visible report is never toggled. */
export async function printDualReport({title,sections}){
 if(!Array.isArray(sections)||sections.length!==2||sections.some(section=>typeof section?.html!=='string'||!section.html.trim()))throw new Error('Prepare os resultados em fardos e R$ antes de imprimir.');
 currentJob?.dispose();
 const root=document.createElement('section');root.id='dual-print-root';root.className='dual-print-root';root.setAttribute('aria-hidden','true');
 root.innerHTML=sections.map((section,index)=>'<section class="dual-print-sheet" data-print-metric="'+(index===0?'fardos':'sales')+'"><header class="dual-print-heading"><span>Distribuidora Demo · Relatório comercial</span><h1>'+esc(title)+'</h1><strong>'+esc(section.title)+'</strong></header><div class="dual-print-content">'+section.html+'</div></section>').join('');
 // Snapshot content is generated by our renderers. Remove live controls and
 // duplicate IDs before attaching both reports to the same document.
 root.querySelectorAll('script,iframe,object,embed,.no-customer-print,.customer-report-actions,[data-print-exclude]').forEach(node=>node.remove());
 root.querySelectorAll('input,select,textarea').forEach(node=>node.remove());
 root.querySelectorAll('button').forEach(node=>{const label=document.createElement('span');label.className=node.className;label.textContent=node.textContent;node.replaceWith(label);});
 root.querySelectorAll('[id]').forEach(node=>node.removeAttribute('id'));
 root.querySelectorAll('[tabindex]').forEach(node=>node.removeAttribute('tabindex'));
 let disposed=false;
 const dispose=()=>{if(disposed)return;disposed=true;window.removeEventListener?.('afterprint',dispose);root.remove();document.body.classList.remove('dual-print-active');if(currentJob?.root===root)currentJob=null;};
 const job={root,dispose};currentJob=job;
 try{
  document.body.appendChild(root);document.body.classList.add('dual-print-active');window.addEventListener('afterprint',dispose,{once:true});
  if(document.fonts?.ready)await settlePrintLayout(document.fonts.ready,1200);
  // Embedded/background tabs may suspend animation frames. Never leave the
  // print control waiting forever for a paint that the browser has paused.
  if(typeof window.requestAnimationFrame==='function')await settlePrintLayout(new Promise(resolve=>window.requestAnimationFrame(()=>window.requestAnimationFrame(resolve))),180);
  if(disposed)return job;
  window.print();return job;
 }catch(error){dispose();throw error;}
}
