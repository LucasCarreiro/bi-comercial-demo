import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

// Deliberately small build step: the source modules use only named imports and
// named const/function/class exports. Unsupported module syntax stops the build.
const directory=path.dirname(fileURLToPath(import.meta.url));
const sourceDirectory=path.join(directory,'public','js');
const identifier=/^[A-Za-z_$][\w$]*$/;
const definitions=new Map();
// Filenames such as client-import.js are string literals, not import.meta.
const hasModuleSyntax=content=>/(?<![\w$.'"\/-])import\s*(?:\(|\.)|^\s*(?:import|export)\b/m.test(content);
const filenames=['analytics.js','representative-aliases.js','api.js','charts.js','registry.js','motion.js','client-catalog.js','client-import.js','planning-api.js','print-report.js','customer-results.js','no-orders.js','representative-model.js','representative-comparison.js','representative-data.js','representative-presentation-data.js','representative-view.js','representative-map.js','representative-pptx.js','representative-intro.js','representative-slides.js','representative-presentation.js','representative-results.js','company-period.js','app.js'];

function fail(file,message){throw new Error(file+': '+message);}
function parseModule(file){
 const original=fs.readFileSync(path.join(sourceDirectory,file),'utf8').replace(/\r\n/g,'\n');
 const imports=[],exports=[];
 let source=original.replace(/^import\s*\{([^}]*)\}\s*from\s*(['"])(\.\/[^'"\n]+)\2\s*;[ \t]*$/gm,(_,list,_quote,dependency)=>{
  const names=list.split(',').map(name=>name.trim()).filter(Boolean);
  if(!names.length||names.some(name=>!identifier.test(name))||new Set(names).size!==names.length)fail(file,'Only unaliased named imports are supported.');
  const importedFile=dependency.slice(2);
  if(!filenames.includes(importedFile))fail(file,'Unknown dependency '+dependency+'.');
  imports.push({file:importedFile,names});return '';
 });
 source=source.replace(/^export\s+((?:async\s+)?function|const|class)\s+([A-Za-z_$][\w$]*)/gm,(_,kind,name)=>{
  if(exports.includes(name))fail(file,'Duplicate export '+name+'.');
  exports.push(name);return kind+' '+name;
 });
 if(source.includes('import.meta.url')){
  if(file!=='api.js')fail(file,'Only the API transport may use import.meta.url.');
  source=source.replace(/\bimport\.meta\.url\b/g,'__moduleURL');
 }
 // vm.Script rejects static module syntax; reject dynamic imports explicitly
 // because they parse as classic JavaScript but would still fail for file URLs.
 if(hasModuleSyntax(source))fail(file,'Unsupported or unconverted module syntax.');
 const importedNames=imports.flatMap(dependency=>dependency.names);
 if(new Set(importedNames).size!==importedNames.length)fail(file,'Duplicate imported binding.');
 definitions.set(file,{file,original,source,imports,exports});
}
filenames.forEach(parseModule);
for(const definition of definitions.values())for(const dependency of definition.imports){
 const provider=definitions.get(dependency.file);
 for(const name of dependency.names)if(!provider.exports.includes(name))fail(definition.file,'Missing export '+name+' in '+dependency.file+'.');
}

function emitModule(file,available){
 const definition=definitions.get(file);
 for(const dependency of definition.imports)if(!available.has(dependency.file))fail(file,'Dependency emitted out of order: '+dependency.file+'.');
 const imports=definition.imports.map(dependency=>'const {'+dependency.names.join(',')+'}=__modules['+JSON.stringify(dependency.file)+'];').join('\n');
 const moduleURL=file==='api.js'?"const __moduleURL=new URL('api.js',__bundleURL).href;\n":'';
 const output='__modules['+JSON.stringify(file)+']=(function(){\n'+imports+'\n'+moduleURL+definition.source.trim()+'\nreturn Object.freeze({'+definition.exports.join(',')+'});\n})();\n';
 available.add(file);return output;
}
function header(files){
 const digest=crypto.createHash('sha256').update(files.map(file=>file+'\n'+definitions.get(file).original).join('\n')).digest('hex');
 return '/* BI Comercial browser bundle. Generated by build_browser.mjs; edit source modules.\n * Sources SHA-256: '+digest+'\n */\n';
}
function buildCore(){
 const files=['analytics.js','representative-aliases.js','api.js'],available=new Set();
 return header(files)+"(function(global){\n'use strict';\nconst __bundleURL=document.currentScript&&document.currentScript.src;\nif(!__bundleURL)throw new Error('Não foi possível identificar o arquivo JavaScript principal.');\nconst __modules=Object.create(null);\n"+files.map(file=>emitModule(file,available)).join('\n')+"global.BICore=Object.freeze({analytics:__modules['analytics.js'],representatives:__modules['representative-aliases.js'],api:__modules['api.js']});\n})(window);\n";
}
function buildApp(){
 const files=['charts.js','registry.js','motion.js','client-catalog.js','client-import.js','planning-api.js','print-report.js','customer-results.js','no-orders.js','representative-model.js','representative-comparison.js','representative-data.js','representative-presentation-data.js','representative-view.js','representative-map.js','representative-pptx.js','representative-intro.js','representative-slides.js','representative-presentation.js','representative-results.js','company-period.js','app.js'],available=new Set(['analytics.js','representative-aliases.js','api.js']);
 return header(files)+"(function(global){\n'use strict';\nif(!global.BICore||!global.BICore.analytics||!global.BICore.representatives||!global.BICore.api)throw new Error('Carregue o arquivo JavaScript principal antes da interface.');\nconst __modules=Object.create(null);\n__modules['analytics.js']=global.BICore.analytics;\n__modules['representative-aliases.js']=global.BICore.representatives;\n__modules['api.js']=global.BICore.api;\n"+files.map(file=>emitModule(file,available)).join('\n')+'})(window);\n';
}
const experienceSource=fs.readFileSync(path.join(sourceDirectory,'experience.js'),'utf8').replace(/^export /gm,'');
const experienceBundle="/* BI local experience layer. */\n(function(){'use strict';\n"+experienceSource+"\nif(document.readyState==='loading')document.addEventListener('DOMContentLoaded',()=>initExperience(),{once:true});else initExperience();\n})();\n";
const bundles=[['core.bundle.js',buildCore()],['app.bundle.js',buildApp()],['experience.bundle.js',experienceBundle]];
// Validate every output before replacing any currently working browser bundle.
for(const [file,content]of bundles){
 if(hasModuleSyntax(content))fail(file,'Generated output still contains module syntax.');
 new vm.Script(content,{filename:file});
}
for(const [file,content]of bundles)fs.writeFileSync(path.join(sourceDirectory,file),content,'utf8');
console.log(JSON.stringify({status:'PASS',bundles:bundles.map(([file,content])=>({file,bytes:Buffer.byteLength(content),sha256:crypto.createHash('sha256').update(content).digest('hex')}))},null,2));
